const DICTS: Partial<Record<Lang, Dict>> = { FR, ES, SW };

/** Translate `source` (English) into the current store.prefs.lang. Falls back to `source` verbatim if untranslated or lang is EN. */
export function t(source: string): string {
  const lang = store.state.prefs.lang;
  if (lang === 'EN') return source;
  return DICTS[lang]?.[source] ?? source;
}
