/**
 * Mallchain Notification Template Catalogue
 *
 * Every notification event in the Mallchain ecosystem has a template here.
 * Each template defines: id, eventType, category, severity, channels, required
 * data fields, and title/body/subject text with {{variable}} placeholders.
 *
 * Categories map to Notification schema `type` enum values:
 *   transaction, security, governance, campaign, badge, marketing, system
 */

function t(id, eventType, category, severity, required, title, body, channels, subject) {
  return {
    id,
    version: 1,
    eventType,
    category,
    severity,
    transactional: true,
    required: required || [],
    channels: channels || ['in_app', 'email'],
    title,
    body,
    subject: subject || title,
  };
}

